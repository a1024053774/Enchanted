// Real default serve/Panes/gates/PTY. The fixture fixes only public launch IDs
// so the controller can approve the exact per-session hook argv in advance.
import assert from "node:assert/strict";
import crypto from "node:crypto";
import { AsyncLocalStorage } from "node:async_hooks";
import { createRequire, syncBuiltinESMExports } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export async function installLaunchGuard(source: string, plan: any) {
  const context = new AsyncLocalStorage<{ spec: any; used: boolean }>();
  const originalUUID = crypto.randomUUID;
  crypto.randomUUID = function (options?: any) {
    const active = context.getStore();
    if (active && !active.used) { active.used = true; return active.spec.launch; }
    return originalUUID(options);
  };
  syncBuiltinESMExports();
  const { Panes } = await import(pathToFileURL(join(source, "workbench/src/panes.ts")).href);
  const require = createRequire(pathToFileURL(join(source, "workbench/src/panes.ts")));
  const pty = require("node-pty"), spawn = pty.spawn, create = Panes.prototype.createThread;
  const used = new Set<string>();
  pty.spawn = (file: string, args: string[], options: any) => {
    const active = context.getStore();
    assert(active, "PTY launch must belong to an approved attempt");
    assert.equal(file, active.spec.shell);
    assert.deepEqual(args, active.spec.shell_argv);
    assert.equal(options.cwd, active.spec.workspace);
    for (const [key, value] of Object.entries(active.spec.checked_env)) assert.equal(options.env[key], value, key);
    // Capability tokens are generated by the unchanged second UUID call and
    // are neither planned nor included in the assertion diagnostics above.
    return Reflect.apply(spawn, pty, [file, args, options]);
  };
  Panes.prototype.createThread = async function (task: any, attempt: any) {
    const spec = plan.launches.find((item: any) => item.fence === attempt.fence);
    assert(spec, "No third launch is authorized by this experiment");
    assert.equal(task.task_id, plan.task); assert.equal(task.project_id, plan.project);
    assert.equal(attempt.workspace, spec.workspace);
    assert(!used.has(spec.launch), "An attempted launch cannot be repeated");
    const approval = JSON.parse(readFileSync(join(plan.fixture, "control", `approval-a${spec.fence}.json`), "utf8"));
    assert.equal(approval.launch, spec.launch); assert.equal(approval.product_revision, plan.product_revision);
    assert(typeof approval.controller_ref === "string" && approval.controller_ref.trim());
    used.add(spec.launch);
    const active = { spec, used: false };
    await context.run(active, async () => {
      await create.call(this, task, attempt);
      assert(active.used, "The planned launch ID was not consumed");
      const record = this.get(attempt.thread_id).record;
      assert.equal(record.id, spec.launch); assert.deepEqual(record.argv, spec.argv);
      this.store.event("fixture_launch_approved", { launch: spec.launch, controller_ref: approval.controller_ref,
        product_revision: plan.product_revision, scope: "public launch ID and argv guard only" }, record);
    });
  };
  return Panes;
}

if (import.meta.main) {
  const [source, planFile, configFile, ready] = process.argv.slice(2);
  assert(source && planFile && configFile && ready && process.argv.length === 6);
  const plan = JSON.parse(readFileSync(planFile, "utf8"));
  await installLaunchGuard(source, plan);
  const { serve } = await import(pathToFileURL(join(source, "workbench/src/daemon.ts")).href);
  await serve(plan.state, JSON.parse(readFileSync(configFile, "utf8")));
  writeFileSync(ready, JSON.stringify({ pid: process.pid, source, plan: planFile, root: plan.state,
    runtime: "production Panes with real PTY and controller-approved public launch IDs" }) + "\n", { flag: "wx" });
}

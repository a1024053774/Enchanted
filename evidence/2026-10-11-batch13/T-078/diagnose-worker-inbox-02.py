"""Read only the failed worker-inbox fixture and persisted protocol outcomes."""
import argparse,json,sqlite3
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);args=p.parse_args()
BASE=Path(__file__).resolve().parent
failed=BASE/'rebased-outside-regression-09a3/worker-inbox'
facts=json.loads((failed/'results.json').read_bytes())
root=Path(facts['fixture']);state=root/'state/state.sqlite3'
client=facts['worker_client'];launch=client['identity']['launch']
assert facts['cleanup_complete'] and not (root/'state/daemon.pid').exists() and not (root/'state/control.sock').exists()
assert not Path(str(state)+'-wal').exists(), 'Do not ignore a live WAL'
# The completed fixture has no WAL. Immutable reads avoid SQLite trying to
# create a shared-memory file in a directory outside the worker write sandbox.
db=sqlite3.connect(state.as_uri()+'?mode=ro&immutable=1',uri=True)
rows=db.execute('SELECT q.launch,q.request_id,q.key,q.input,r.data FROM relay_requests q JOIN relay_results r ON r.key=q.key ORDER BY q.created_at').fetchall()
replies=[]
for owner,ident,key,raw,data in rows:
    value=json.loads(data);request=json.loads(raw)
    replies.append({'launch':owner,'request_id':ident,'key':key,'command':request['command'],
                    'old_lookup_key':'id:'+ident,'old_lookup_matches':key=='id:'+ident,'reply':value})
events=db.execute('SELECT seq,type,data FROM orchestration_events WHERE type IN (?,?) ORDER BY seq',('turn_end_signal','relay_replayed')).fetchall()
db.close()
r={'status':'PASS','scope':'只读诊断原失败；不是重试或产品通过','fixture':str(root),'launch':launch,
   'queued_client_calls':len(client['commands']),'persisted_replies':replies,
   'lifecycle':[{'seq':seq,'type':kind,'data':json.loads(data)} for seq,kind,data in events],
   'classification':'Stale fixture receipt lookup: id:<request> no longer identifies id:<launch>:<request>',
   'product_result_claim':'All original request outcomes exist; observed={} is generated by fixture lookup, not absent daemon replies',
   'original_status':facts['status'],'original_attempt':facts['attempt'],'cleanup_complete':facts['cleanup_complete'],'real_model_turns':0}
args.output.mkdir()
(args.output/'diagnosis.json').write_text(json.dumps(r,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'status':r['status'],'classification':r['classification'],'replies':[{'command':v['command'],'error':v['reply'].get('error'),'has_entry':'entry' in v['reply'],'old_lookup_matches':v['old_lookup_matches']} for v in replies]},ensure_ascii=False))

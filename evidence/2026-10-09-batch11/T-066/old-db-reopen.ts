import assert from "node:assert/strict";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { join } from "node:path";
import { A2AGates } from "/Users/luckye/Documents/Code/synara/packages/a2a-gates/src/core.ts";
const out = import.meta.dirname;
const root = "/Volumes/WD-Elements/dev-cache/synara/instances/t066-old-db-reopen";
mkdirSync(root);
const path = join(root, "state.sqlite3");
copyFileSync(join(out, "red02/state.sqlite3"), path);
const beforeDB = new DatabaseSync(path);
const rows = beforeDB.prepare("SELECT seq,time,task,attempt,type,details FROM events ORDER BY seq").all();
const columns = beforeDB.prepare("PRAGMA table_info(events)").all();
beforeDB.close();
const gates = new A2AGates(root);
const result = await gates.call({ command: "events", task: "t066" });
gates.close();
const afterDB = new DatabaseSync(path);
assert.deepEqual(afterDB.prepare("SELECT seq,time,task,attempt,type,details FROM events ORDER BY seq").all(), rows);
assert.deepEqual(afterDB.prepare("PRAGMA table_info(events)").all(), columns);
afterDB.close();
const expected = JSON.parse(readFileSync(join(out, "red02/executor-event.json"), "utf8"));
const event = result.events!.find((value) => value.seq === expected.seq)!;
assert.deepEqual(event.details, expected.details);
assert.equal(Object.hasOwn(event.details as object, "caller_thread"), false);
assert.equal(Object.hasOwn(event.details as object, "caller_turn"), false);
copyFileSync(path, join(out, "old-db-reopened.sqlite3"));
writeFileSync(join(out, "old-db-reopen.json"), JSON.stringify({ status: "PASS", columns, rows, event }, null, 2) + "\n", { flag: "wx" });
console.log("PASS candidate core reopened actual baseline database; all raw event rows and columns unchanged");
